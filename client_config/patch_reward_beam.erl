-module(patch_reward_beam).
-export([main/0]).

main() ->
    Orig = "/data/sszg_code/v200408/server/ebin/dungeon_data.beam",
    OutDir = "/tmp/dungeon_data_client75",
    Out = OutDir ++ "/dungeon_data.beam",
    ok = filelib:ensure_dir(Out),
    BF = beam_disasm:file(Orig),
    {beam_file, Mod, Exports, Attrs, _CompileInfo, Funs} = BF,
    {ok, {_, [{"Code", CodeBin}]}} = beam_lib:chunks(Orig, ["Code"]),
    <<_Word:32, _Format:32, _Highest:32, _NumLabels0:32, _NumFuncs:32, _Rest/binary>> = CodeBin,
    ExportNames = [{N, A} || {N, A, _} <- Exports],
    NewFuns = [case F of
                   {function, ext_reward, 1, _, _} -> make_ext_fun(client_rewards());
                   {function, N, A, E, Is} -> {function, N, A, E, strip_lines(Is)}
               end || F <- Funs],
    Code = {Mod, ExportNames, Attrs, NewFuns, 1000},
    {ok, NewBeam} = beam_asm:module(Code, [], "/server/src/data/dungeon_data.erl", []),
    ok = file:write_file(Out, NewBeam),
    io:format("wrote=~s bytes=~p rows=~p~n", [Out, byte_size(NewBeam), length(client_rewards())]),
    ok.

strip_lines(Is) ->
    [I || I <- Is, not is_line_instr(I)].

is_line_instr({line, _}) -> true;
is_line_instr(_) -> false.

make_ext_fun(Rows) ->
    {Pairs0, Bodies0, Next0} =
        lists:foldl(
          fun(R, {Pairs, Bodies, Label}) ->
              Id = maps:get(id, R),
              NewLabel = Label + 1,
              Old = dungeon_data:ext_reward(Id),
              Map = case maps:find(notice, Old) of
                        {ok, Notice} -> maps:put(notice, Notice, R);
                        error -> R
                    end,
              { [[{integer, Id}, {f, NewLabel}] | Pairs],
                Bodies ++ [{label, NewLabel},
                           {move, {literal, Map}, {x, 0}},
                           return],
                NewLabel}
          end, {[], [], 900}, Rows),
    DefaultLabel = Next0 + 1,
    Pairs = lists:append(lists:reverse(Pairs0)),
    {function, ext_reward, 1, 706,
     [{label, 705},
      {func_info, {atom, dungeon_data}, {atom, ext_reward}, 1},
      {label, 706},
      {test, is_integer, {f, DefaultLabel}, [{x, 0}]},
      {select_val, {x, 0}, {f, DefaultLabel},
       {list, Pairs}} | Bodies0] ++
      [{label, DefaultLabel}, {move, {atom, undefined}, {x, 0}}, return]}.

